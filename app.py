# 7. FAILURE RATE BY DEVICE TYPE (SECTION D)
# =====================================================================
st.markdown("---")
st.subheader("Section D: Failure Rate by Device Type (Normalized)")

st.caption("Calculates the exact failure percentage within each device category: Rate (%) = (Failures in Type / Total Devices in Type) × 100.")

# Calculate true category rates using current filtered dataset
grouped_stats = []
active_dev_df = df_predictions if not selected_regions else df_predictions[df_predictions["region"].isin(selected_regions)]

for dev_type, group in active_dev_df.groupby("device_type"):
    total_dev = len(group)
    actual_f = group["actual_failure"].sum()
    pred_f = group["predicted_failure"].sum()

    actual_rate = (actual_f / total_dev * 100) if total_dev > 0 else 0.0
    pred_rate = (pred_f / total_dev * 100) if total_dev > 0 else 0.0

    grouped_stats.append({
        "Device Type": dev_type,
        "Total Devices": total_dev,
        "Actual Failures": actual_f,
        "Predicted Failures": pred_f,
        "Actual Failure Rate (%)": round(actual_rate, 2),
        "Predicted Failure Rate (%)": round(pred_rate, 2)
    })

df_rates = pd.DataFrame(grouped_stats)

# Melt for side-by-side grouped bar chart
df_rates_melted = df_rates.melt(
    id_vars=["Device Type", "Total Devices"],
    value_vars=["Actual Failure Rate (%)", "Predicted Failure Rate (%)"],
    var_name="Rate Type",
    value_name="Failure Rate (%)"
)

fig_rates = px.bar(
    df_rates_melted,
    x="Device Type",
    y="Failure Rate (%)",
    color="Rate Type",
    barmode="group",
    text="Failure Rate (%)",
    color_discrete_map={
        "Actual Failure Rate (%)": "#f87171",
        "Predicted Failure Rate (%)": "#38bdf8"
    }
)
fig_rates.update_traces(texttemplate="%{text:.1f}%", textposition="outside")
fig_rates.update_layout(
    margin=dict(l=20, r=20, t=30, b=20),
    height=360,
    paper_bgcolor="rgba(0,0,0,0)",
    plot_bgcolor="rgba(0,0,0,0)",
    font=dict(color="#f8fafc"),
    legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
    xaxis=dict(title="", showgrid=False),
    yaxis=dict(title="Rate within Device Category (%)", showgrid=True, gridcolor="#334155")
)
st.plotly_chart(fig_rates, use_container_width=True)


