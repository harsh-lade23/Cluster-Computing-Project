PREDICTIONS_CSV = os.path.join("outputs", "predictions", "test_predictions.csv")
METRICS_JSON = os.path.join("outputs", "evaluation_results", "metrics.json")


@st.cache_data
def load_dashboard_data():
    """Loads predictions and metrics from outputs directory."""
    if not os.path.exists(PREDICTIONS_CSV):
        st.error(f"⚠️ Predictions file not found: `{PREDICTIONS_CSV}`. Please execute `python3 src/train_model.py` first.")
        st.stop()

    if not os.path.exists(METRICS_JSON):
        st.error(f"⚠️ Metrics file not found: `{METRICS_JSON}`. Please execute `python3 src/train_model.py` first.")
        st.stop()

    df_preds = pd.read_csv(PREDICTIONS_CSV)
    with open(METRICS_JSON, "r", encoding="utf-8") as f:
        metrics = json.load(f)

    return df_preds, metrics


